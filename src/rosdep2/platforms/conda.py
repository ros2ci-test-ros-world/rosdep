"""
Conda as a rosdep platform, installed through pixi.

Conda is a platform of its own in the rosdep rules, as Ubuntu is: a rule
names conda packages under the ``conda`` key, and the same rule serves
every operating system the conda packages exist for. Select it with
``--os=conda:<anything>``.

Three things differ from the system package managers:

* **A key resolves only if its packages are pinned.** The rules give
  names. A constraints file for the ROS distribution gives the versions,
  as an Ubuntu release does for apt. A conda package with no pin is not
  available, and the key that names it does not resolve.

* **The whole environment is solved at once.** ``rosdep install`` writes a
  pixi manifest holding every resolved package at its pinned version and
  runs one ``pixi install``, where apt is run once per key.

* **rosdep owns the manifest.** It is a generated file. Running
  ``rosdep install`` again adds what is new and moves any package whose
  pin has changed, and never removes anything, which is how rosdep
  behaves with apt. ``--reinstall`` writes the manifest afresh, holding
  only what is needed now.

The constraints file is YAML::

    channels: [conda-forge]
    base:
      python: 3.12.*
    pins:
      cmake: 3.31.*
      pytest: 8.*

``channels`` are searched in order. ``base`` packages are always in the
environment. ``pins`` give the version of every other package a rule may
name. ROS packages, named ``ros-<distro>-<name>``, come from the first
channel at whatever version it holds and need no pin.

Where things are:

* ``ROSDEP_CONDA_CONSTRAINTS`` is the path or URL of the constraints
  file. Without it, the file is ``<distro>/conda/constraints.yaml`` beside
  the rosdistro index named by ``ROSDISTRO_INDEX_URL``.
* ``ROSDEP_PIXI_MANIFEST`` is the path of the manifest. Without it, the
  manifest is ``pixi.toml`` in the current directory.
"""

import json
import os
import platform
import re
import subprocess
import sys

from rospkg.os_detect import OS_CONDA

import yaml

from ..core import InvalidData
from ..installers import PackageManagerInstaller
from ..shell_utils import read_stdout

CONDA_INSTALLER = 'conda'

CONSTRAINTS_ENV = 'ROSDEP_CONDA_CONSTRAINTS'
MANIFEST_ENV = 'ROSDEP_PIXI_MANIFEST'

# The first line of every manifest rosdep writes. rosdep refuses to touch
# a manifest without it, so it never overwrites one a person wrote.
MANIFEST_MARKER = '# Generated by rosdep. Do not edit: your changes will be overwritten.'

# What a conda package name or version spec may contain. Both are written
# into a manifest, so anything else is refused outright.
_NAME = re.compile(r'^[a-z0-9][a-z0-9._-]*$')
_SPEC = re.compile(r'^[A-Za-z0-9.*+!_,<>=~| -]+$')


def register_installers(context):
    context.set_installer(CONDA_INSTALLER, CondaInstaller())


def register_platforms(context):
    context.add_os_installer_key(OS_CONDA, CONDA_INSTALLER)
    context.set_default_os_installer_key(OS_CONDA, lambda self: CONDA_INSTALLER)


def ros_distro():
    """
    :returns: the ROS distribution being resolved for, which rosdep takes
      from ``--rosdistro`` or the environment, or ``None``.
    """
    return os.environ.get('ROS_DISTRO') or None


def constraints_location():
    """
    :returns: the path or URL of the constraints file.
    :raises: :exc:`InvalidData` if it cannot be worked out.
    """
    explicit = os.environ.get(CONSTRAINTS_ENV)
    if explicit:
        return explicit
    distro = ros_distro()
    if not distro:
        raise InvalidData(
            'conda packages are pinned per ROS distribution: '
            'give --rosdistro, or set ROS_DISTRO or %s' % CONSTRAINTS_ENV)
    index = os.environ.get('ROSDISTRO_INDEX_URL')
    if not index:
        raise InvalidData(
            'cannot find the conda constraints for %s: '
            'set ROSDISTRO_INDEX_URL or %s' % (distro, CONSTRAINTS_ENV))
    return '%s/%s/conda/constraints.yaml' % (index.rsplit('/', 1)[0], distro)


def _read(location):
    if re.match(r'^[a-z][a-z0-9+.-]*://', location):
        try:
            from urllib.request import urlopen
        except ImportError:
            from urllib2 import urlopen
        with urlopen(location, timeout=30) as response:
            return response.read().decode('utf-8')
    with open(location, 'r') as f:
        return f.read()


class Constraints(object):
    """
    The versions conda packages are held to for one ROS distribution.
    """

    def __init__(self, channels, base, pins, source='<data>'):
        self.channels = channels
        self.base = base
        self.pins = pins
        self.source = source

    @staticmethod
    def parse(text, source='<data>'):
        """
        :raises: :exc:`InvalidData` if the text is not a constraints file.
        """
        try:
            data = yaml.safe_load(text)
        except yaml.YAMLError as e:
            raise InvalidData('%s is not valid YAML: %s' % (source, e))
        if not isinstance(data, dict):
            raise InvalidData('%s must be a mapping' % source)
        unknown = sorted(set(data) - {'channels', 'base', 'pins'})
        if unknown:
            raise InvalidData('%s has unknown entries: %s' % (source, ', '.join(unknown)))

        channels = data.get('channels')
        if not isinstance(channels, list) or not channels or \
                not all(isinstance(c, str) and c and not re.search(r'[\s"\\]', c) for c in channels):
            raise InvalidData('%s: "channels" must be a list of channel names or URLs' % source)

        def versions(section):
            entries = data.get(section) or {}
            if not isinstance(entries, dict):
                raise InvalidData('%s: "%s" must map package names to versions' % (source, section))
            out = {}
            for name, spec in entries.items():
                # YAML reads an unquoted 3.12 as a number.
                spec = str(spec)
                if not isinstance(name, str) or not _NAME.match(name):
                    raise InvalidData('%s: %r is not a conda package name' % (source, name))
                if not _SPEC.match(spec):
                    raise InvalidData('%s: %r is not a version for %s' % (source, spec, name))
                out[name] = spec
            return out

        return Constraints(channels, versions('base'), versions('pins'), source)

    def spec_for(self, package):
        """
        :returns: the version spec to install *package* at, or ``None`` if
          the package is not pinned and so is not available.
        """
        if package in self.pins:
            return self.pins[package]
        if package in self.base:
            return self.base[package]
        distro = ros_distro()
        if distro and package.startswith('ros-%s-' % distro.replace('_', '-')):
            # A ROS package, from our own channel, at the version it holds.
            return '*'
        return None


_constraints_cache = {}


def load_constraints():
    """
    :returns: the :class:`Constraints` in force, read once per location.
    :raises: :exc:`InvalidData` if they cannot be read.
    """
    location = constraints_location()
    if location not in _constraints_cache:
        try:
            text = _read(location)
        except Exception as e:
            raise InvalidData('cannot read the conda constraints at %s: %s' % (location, e))
        _constraints_cache[location] = Constraints.parse(text, location)
    return _constraints_cache[location]


def manifest_path():
    return os.environ.get(MANIFEST_ENV) or os.path.join(os.getcwd(), 'pixi.toml')


def conda_platform():
    """
    :returns: conda's name for the platform this is running on.
    """
    machine = platform.machine().lower()
    arm = machine in ('arm64', 'aarch64')
    if sys.platform.startswith('win'):
        return 'win-arm64' if arm else 'win-64'
    if sys.platform == 'darwin':
        return 'osx-arm64' if arm else 'osx-64'
    return 'linux-aarch64' if arm else 'linux-64'


def read_manifest(path):
    """
    :returns: the dependencies in a manifest rosdep wrote, as a dict of
      package name to version spec; empty if there is no manifest.
    :raises: :exc:`InvalidData` if the file is not one rosdep wrote.
    """
    if not os.path.exists(path):
        return {}
    with open(path, 'r') as f:
        lines = f.read().splitlines()
    if not lines or lines[0].strip() != MANIFEST_MARKER:
        raise InvalidData(
            '%s was not written by rosdep, and rosdep will not overwrite it. '
            'Move it away, or point %s somewhere else.' % (path, MANIFEST_ENV))
    dependencies = {}
    section = None
    for line in lines:
        line = line.strip()
        if line.startswith('['):
            section = line
        elif section == '[dependencies]' and '=' in line and not line.startswith('#'):
            name, spec = line.split('=', 1)
            try:
                dependencies[json.loads(name.strip())] = json.loads(spec.strip())
            except ValueError:
                raise InvalidData('%s has a line rosdep cannot read: %s' % (path, line))
    return dependencies


def write_manifest(path, constraints, dependencies):
    """
    Write a pixi manifest holding *dependencies*, a dict of package name
    to version spec.
    """
    def quoted(text):
        # A JSON string is a valid TOML basic string.
        return json.dumps(text)

    lines = [
        MANIFEST_MARKER,
        '',
        '[workspace]',
        'name = "rosdep"',
        'channels = [%s]' % ', '.join(quoted(c) for c in constraints.channels),
        'platforms = [%s]' % quoted(conda_platform()),
        '',
        '[dependencies]',
    ]
    for name in sorted(dependencies):
        lines.append('%s = %s' % (quoted(name), quoted(dependencies[name])))
    directory = os.path.dirname(path)
    if directory and not os.path.isdir(directory):
        os.makedirs(directory)
    # Written whole and then moved into place, so a reader never sees half.
    temporary = path + '.tmp'
    with open(temporary, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    os.replace(temporary, path)


def merged_dependencies(existing, constraints, packages, afresh):
    """
    Work out what the manifest should hold.

    :param existing: what the manifest holds now.
    :param packages: the conda packages wanted now.
    :param afresh: start from nothing, as ``--reinstall`` asks.
    :returns: dict of package name to version spec.
    :raises: :exc:`InvalidData` if a wanted package is not pinned.
    """
    dependencies = {} if afresh else dict(existing)
    wanted = list(constraints.base) + list(packages)
    for name in wanted:
        if constraints.spec_for(name) is None:
            raise InvalidData(
                'conda package %s has no pin in %s' % (name, constraints.source))
        dependencies.setdefault(name, None)
    # Everything takes its current pin, so a package whose pin changed
    # moves. A package that lost its pin since it was added keeps the
    # version it has: a rerun never removes.
    for name in dependencies:
        spec = constraints.spec_for(name)
        if spec is not None:
            dependencies[name] = spec
        elif dependencies[name] is None:
            dependencies[name] = '*'
    return dependencies


def conda_detect(packages):
    """
    :returns: the *packages* the manifest already holds at their pinned
      versions. A package whose pin has changed counts as not installed,
      so that it is moved.
    """
    try:
        existing = read_manifest(manifest_path())
        constraints = load_constraints()
    except InvalidData:
        return []
    return [p for p in packages if p in existing and existing[p] == constraints.spec_for(p)]


class CondaInstaller(PackageManagerInstaller):

    def __init__(self):
        super(CondaInstaller, self).__init__(conda_detect)
        # The environment belongs to whoever runs rosdep.
        self.as_root = False
        self.sudo_command = ''

    def resolve(self, rosdep_args):
        """
        A rule's packages, provided every one of them is pinned.

        :raises: :exc:`InvalidData` if a package has no pin, which makes
          the key unresolved.
        """
        packages = super(CondaInstaller, self).resolve(rosdep_args)
        constraints = load_constraints()
        for package in packages:
            if not isinstance(package, str) or not _NAME.match(package):
                raise InvalidData('%r is not a conda package name' % (package,))
        unpinned = [p for p in packages if constraints.spec_for(p) is None]
        if unpinned:
            raise InvalidData(
                'no pin for conda package%s %s in %s' % (
                    '' if len(unpinned) == 1 else 's', ', '.join(unpinned), constraints.source))
        return packages

    def get_version_strings(self):
        try:
            output = read_stdout(['pixi', '--version'])
        except (OSError, subprocess.CalledProcessError):
            return ['pixi not-found']
        return [output.strip() or 'pixi unknown']

    def get_install_command(self, resolved, interactive=True, reinstall=False, quiet=False):
        """
        Bring the manifest up to date, and return the one command that
        makes the environment match it.
        """
        packages = self.get_packages_to_install(resolved, reinstall=reinstall)
        if not packages and not reinstall:
            return []
        path = manifest_path()
        constraints = load_constraints()
        existing = {} if reinstall else read_manifest(path)
        if reinstall and os.path.exists(path):
            # Still refuse to replace a manifest a person wrote.
            read_manifest(path)
        write_manifest(path, constraints, merged_dependencies(existing, constraints, resolved, afresh=reinstall))
        command = ['pixi', 'install', '--manifest-path', path]
        if quiet:
            command.append('--quiet')
        return [command]
